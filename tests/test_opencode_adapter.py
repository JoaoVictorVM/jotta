from __future__ import annotations

import fnmatch
import json
import subprocess
from pathlib import Path

import pytest

from jotta.cli import main
from jotta.core.state import JSONDict


def adapt(project: Path, capsys: pytest.CaptureFixture[str], *extra: str) -> tuple[int, JSONDict]:
    code = main(["--root", str(project), "adapter", "opencode", *extra])
    data: JSONDict = json.loads(capsys.readouterr().out)
    return code, data


def config(project: Path) -> JSONDict:
    text = (project / ".opencode" / "opencode.jsonc").read_text(encoding="utf-8")
    header, body = text.split("\n", 1)
    assert header.startswith("// generated by jotta from .jotta/policy/permissions.md")
    data: JSONDict = json.loads(body)
    return data


def effect(rules: list[JSONDict], action: str, resource: str) -> str:
    """The effect OpenCode gives a resource: the last matching rule wins, and the base default is allow."""
    matches = [
        item["effect"] for item in rules if item["action"] == action and fnmatch.fnmatchcase(resource, item["resource"])
    ]
    return str(matches[-1]) if matches else "allow"


def test_the_adapter_writes_config_agents_and_skills(project: Path, capsys: pytest.CaptureFixture[str]) -> None:
    code, result = adapt(project, capsys)
    assert (code, result["status"], result["skipped"]) == (0, "configured", [])
    assert config(project)["$schema"] == "https://opencode.ai/config.json"
    agents = {path.stem for path in (project / ".opencode" / "agents").glob("*.md")}
    assert agents == {path.stem for path in (project / ".jotta" / "agents").glob("*.md")}
    skills = {path.parent.name for path in (project / ".opencode" / "skills").glob("*/SKILL.md")}
    assert skills == {path.parent.name for path in (project / ".jotta" / "skills").glob("*/SKILL.md")}
    _, again = adapt(project, capsys)
    assert again["written"] == []


@pytest.mark.parametrize(
    ("action", "resource", "expected"),
    [
        ("read", "/work/app/.env", "deny"),
        ("read", ".env.local", "deny"),
        ("edit", "/work/app/config/credentials.json", "deny"),
        ("read", "/work/app/.env.example", "allow"),
        ("read", "/srv/keys/.ssh/id_ed25519.pub", "deny"),
        ("read", "/work/app/src/env.py", "allow"),
        ("shell", "git push --force origin main", "deny"),
        ("shell", "git push origin main -f", "deny"),
        ("shell", "git push origin +main", "deny"),
        ("shell", "git push --follow-tags origin main", "allow"),
        ("shell", "git push -u origin feat/x", "allow"),
        ("shell", "git reset --hard HEAD~1", "deny"),
        ("shell", "git commit -m x --no-verify", "deny"),
        ("shell", "gh pr merge 3 --merge --admin", "deny"),
        ("shell", "jotta --root . scope allow src/x.py", "deny"),
        ("shell", "jotta scope show", "allow"),
        ("external_directory", "/tmp/x", "ask"),
    ],
)
def test_permission_rules_mirror_the_deny_list(
    project: Path, capsys: pytest.CaptureFixture[str], action: str, resource: str, expected: str
) -> None:
    adapt(project, capsys)
    assert effect(config(project)["permissions"], action, resource) == expected


def frontmatter(path: Path) -> str:
    return path.read_text(encoding="utf-8").split("---\n")[1]


def test_reviewers_are_read_only_subagents(project: Path, capsys: pytest.CaptureFixture[str]) -> None:
    adapt(project, capsys)
    agents = project / ".opencode" / "agents"
    reviewer = frontmatter(agents / "reviewer.md")
    assert "mode: subagent" in reviewer
    assert '  - action: edit\n    resource: "*"\n    effect: deny' in reviewer
    assert '  - action: shell\n    resource: "*"\n    effect: deny' in reviewer
    spec_author = frontmatter(agents / "spec-author.md")
    assert "action: shell" in spec_author and "action: edit" not in spec_author
    assert "\npermissions:" not in frontmatter(agents / "implementer.md")
    assert "# Agent: reviewer" in (agents / "reviewer.md").read_text(encoding="utf-8")


def test_a_user_config_is_never_replaced(project: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = project / ".opencode"
    target.mkdir()
    (target / "opencode.json").write_text('{"model": "mine"}', encoding="utf-8")
    (target / "agents").mkdir()
    (target / "agents" / "reviewer.md").write_text("my reviewer\n", encoding="utf-8")
    code, result = adapt(project, capsys)
    assert code == 0
    assert result["skipped"] == [".opencode/agents/reviewer.md", ".opencode/opencode.jsonc"]
    assert not (target / "opencode.jsonc").exists()
    assert (target / "agents" / "reviewer.md").read_text(encoding="utf-8") == "my reviewer\n"


def test_doctor_checks_the_rules_only_in_an_opencode_project(project: Path, capsys: pytest.CaptureFixture[str]) -> None:
    main(["--root", str(project), "doctor"])
    assert "OpenCode" not in capsys.readouterr().out
    (project / ".opencode").mkdir()
    main(["--root", str(project), "doctor"])
    assert "OpenCode permission rules not generated" in capsys.readouterr().out
    adapt(project, capsys)
    main(["--root", str(project), "doctor"])
    assert "OpenCode" not in capsys.readouterr().out


def test_install_configures_opencode(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    project = tmp_path / "project"
    subprocess.run(["git", "init", "-q", str(project)], check=True)
    assert main(["install", "--target", str(project)]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["opencode"]["error"] is None
    assert (project / ".opencode" / "opencode.jsonc").is_file()
    exclude = (project / ".git" / "info" / "exclude").read_text(encoding="utf-8").splitlines()
    assert "/.opencode/" in exclude
