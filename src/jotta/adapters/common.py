"""Pieces shared by the agent adapters: planning writes, merging hook files and building skill entries.

Every generated file carries a ``generated by jotta from <source>`` marker. A file without the marker belongs to the
user and is never overwritten: it is reported as skipped. Hook files are the exception, since they are merged: the
adapter adds its commands and keeps everything else.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from jotta.core.paths import ProjectPaths
from jotta.core.state import JSONDict

MARKER = "generated by jotta from"

HookSpec = dict[str, JSONDict]


class SettingsError(ValueError):
    """Raised when an existing hook file cannot be merged."""


@dataclass
class AdapterPlan:
    """Every file an adapter would write, computed before writing."""

    root: Path
    writes: dict[Path, str] = field(default_factory=dict)
    unchanged: list[Path] = field(default_factory=list)
    skipped: list[Path] = field(default_factory=list)
    error: str | None = None

    def relative(self, path: Path) -> str:
        return path.relative_to(self.root).as_posix()

    def summary(self) -> JSONDict:
        return {
            "written": sorted(self.relative(path) for path in self.writes),
            "unchanged": len(self.unchanged),
            "skipped": sorted(self.relative(path) for path in self.skipped),
            "error": self.error,
        }


def hook_group(matcher: str | None, command: str) -> JSONDict:
    group: JSONDict = {"hooks": [{"type": "command", "command": command}]}
    return {"matcher": matcher, **group} if matcher else group


def commands_in(groups: list[JSONDict]) -> set[str]:
    return {
        str(hook.get("command"))
        for group in groups
        if isinstance(group, dict)
        for hook in group.get("hooks") or []
        if isinstance(hook, dict)
    }


def merge_hooks(current: JSONDict, spec: HookSpec) -> JSONDict:
    """Add the hooks of ``spec`` to ``current``, keeping every existing key and hook."""
    merged = dict(current)
    hooks = merged.get("hooks", {})
    if not isinstance(hooks, dict):
        raise SettingsError("`hooks` is not an object")
    hooks = dict(hooks)
    for event, entry in spec.items():
        groups = hooks.get(event, [])
        if not isinstance(groups, list):
            raise SettingsError(f"`hooks.{event}` is not a list")
        if entry["command"] not in commands_in(groups):
            groups = [*groups, hook_group(entry["matcher"], str(entry["command"]))]
        hooks[event] = groups
    merged["hooks"] = hooks
    return merged


def missing_hook_events(path: Path, spec: HookSpec) -> list[str]:
    """The events of ``spec`` whose command is absent from the hook file at ``path``."""
    try:
        current = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return list(spec)
    hooks = current.get("hooks") if isinstance(current, dict) else None
    if not isinstance(hooks, dict):
        return list(spec)
    return [
        event
        for event, entry in spec.items()
        if not isinstance(hooks.get(event), list) or entry["command"] not in commands_in(hooks[event])
    ]


def render_json(data: JSONDict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def stage_hooks(plan: AdapterPlan, path: Path, spec: HookSpec, paths: ProjectPaths) -> None:
    """Plan merging ``spec`` into the JSON hook file at ``path``, or record why it cannot be merged."""
    try:
        current = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        if not isinstance(current, dict):
            raise SettingsError("the file is not a JSON object")
        stage(plan, path, render_json(merge_hooks(current, spec)), owned=True)
    except (json.JSONDecodeError, SettingsError) as exc:
        plan.error = f"cannot merge {paths.relative(path)}: {exc}"


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == '"':
        try:
            return str(json.loads(value))
        except json.JSONDecodeError:
            return value
    return value


def split_frontmatter(text: str) -> tuple[JSONDict, str]:
    """Read the simple ``key: value`` frontmatter of a skill and return it with the body."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end < 0:
        return {}, text
    fields: JSONDict = {}
    for line in text[4:end].splitlines():
        key, separator, value = line.partition(":")
        if separator:
            fields[key.strip()] = unquote(value.strip())
    return fields, text[end + 4 :].lstrip("\n")


def first_paragraph(body: str) -> str:
    """The first prose paragraph of an agent role, used as the subagent description."""
    lines = body.splitlines()
    for index, line in enumerate(lines):
        if not line.strip() or line.startswith("#"):
            continue
        paragraph = []
        for item in lines[index:]:
            if not item.strip() or item.startswith("#"):
                break
            paragraph.append(item.strip())
        return " ".join(paragraph)
    return ""


def frontmatter(fields: dict[str, str]) -> str:
    """YAML frontmatter; the description is quoted, since prose may contain characters YAML treats as syntax."""
    lines = [
        f"{key}: {json.dumps(value, ensure_ascii=False) if key == 'description' else value}"
        for key, value in fields.items()
        if value
    ]
    return "\n".join(["---", *lines, "---"])


def marker(origin: str, agent: str) -> str:
    return f"{MARKER} {origin}; edit the source and run `jotta adapter {agent}`"


def skill_file(source: Path, paths: ProjectPaths, agent: str) -> str | None:
    """A skill entry with the canonical name and description that sends the agent to the harness skill."""
    fields, _body = split_frontmatter(source.read_text(encoding="utf-8"))
    name, description = str(fields.get("name") or ""), str(fields.get("description") or "")
    if not name or not description:
        return None
    origin = paths.relative(source)
    return "\n".join(
        [
            frontmatter({"name": name, "description": description}),
            "",
            f"<!-- {marker(origin, agent)} -->",
            "",
            f"Read `{origin}` completely and follow it.",
            f"Resolve its relative links from `{paths.relative(source.parent)}/`.",
            "",
        ]
    )


def stage_skills(plan: AdapterPlan, paths: ProjectPaths, target: Path, agent: str) -> None:
    """Plan one entry under ``target`` for every harness skill."""
    for source in sorted(paths.skills.glob("*/SKILL.md")):
        content = skill_file(source, paths, agent)
        if content is not None:
            stage(plan, target / source.parent.name / "SKILL.md", content)


def is_generated(path: Path) -> bool:
    try:
        return MARKER in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def stage(plan: AdapterPlan, path: Path, content: str, owned: bool = False) -> None:
    """Plan writing ``content`` to ``path`` unless it is identical or belongs to the user."""
    if path.exists():
        if path.read_text(encoding="utf-8") == content:
            plan.unchanged.append(path)
            return
        if not owned and not is_generated(path):
            plan.skipped.append(path)
            return
    plan.writes[path] = content


def apply_adapter(plan: AdapterPlan) -> None:
    for path, content in plan.writes.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
